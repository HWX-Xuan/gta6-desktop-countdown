using System.Diagnostics;
using System.IO;
using System.Text;
using Microsoft.Win32;

namespace Gta6Countdown;

internal static class StartupManager
{
    private const string RunKeyPath = @"Software\Microsoft\Windows\CurrentVersion\Run";
    private const string ValueName = "GTA6Countdown";

    public static bool IsEnabled()
    {
        using var key = Registry.CurrentUser.OpenSubKey(RunKeyPath, writable: false);
        return key?.GetValue(ValueName) is string value && !string.IsNullOrWhiteSpace(value);
    }

    public static void SetEnabled(bool enabled)
    {
        using var key = Registry.CurrentUser.OpenSubKey(RunKeyPath, writable: true)
            ?? throw new InvalidOperationException("Cannot open the current-user startup registry key.");

        if (!enabled)
        {
            key.DeleteValue(ValueName, throwOnMissingValue: false);
            WidgetLog.Write("Autostart disabled (Run key removed).");
            return;
        }

        var command = BuildLaunchCommand();
        key.SetValue(ValueName, command, RegistryValueKind.String);
        WidgetLog.Write($"Autostart enabled: {command}");
    }

    /// <summary>
    /// Builds a startup command that re-enters through the .NET host. The app is
    /// normally hosted by dotnet.exe during development, so registering the process
    /// path alone would start a bare dotnet process; the small VBS wrapper keeps the
    /// launch silent and correct for both direct and hosted launches.
    /// </summary>
    private static string BuildLaunchCommand()
    {
        var dotnet = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.ProgramFiles),
            "dotnet",
            "dotnet.exe");

        var entryAssembly = typeof(StartupManager).Assembly.Location;
        var exePath = Environment.ProcessPath
            ?? Process.GetCurrentProcess().MainModule?.FileName
            ?? string.Empty;

        // Prefer our AUMID-bearing Start Menu shortcut. Launching through it
        // keeps the taskbar identity as "GTA VI 倒计时" on every sign-in.
        var startMenuShortcut = Path.Combine(
            Environment.GetFolderPath(Environment.SpecialFolder.Programs),
            "GTA VI 倒计时.lnk");
        if (File.Exists(startMenuShortcut))
        {
            return $"\"{startMenuShortcut}\"";
        }

        if (File.Exists(dotnet) && !string.IsNullOrWhiteSpace(entryAssembly))
        {
            var launcher = Path.Combine(WidgetPaths.DataDirectory, "GTA6CountdownLauncher.vbs");
            var script =
                "' Generated by GTA6Countdown. Starts the widget without a console window.\r\n" +
                "Option Explicit\r\n" +
                "Dim sh\r\n" +
                "Set sh = CreateObject(\"WScript.Shell\")\r\n" +
                $"sh.CurrentDirectory = \"{Path.GetDirectoryName(entryAssembly)}\"\r\n" +
                $"sh.Run \"\"\"{dotnet}\"\" \"\"{entryAssembly}\"\"\", 0, False\r\n";
            File.WriteAllText(launcher, script, Encoding.Unicode);
            return $"wscript.exe \"{launcher}\"";
        }

        if (!string.IsNullOrWhiteSpace(exePath))
        {
            return $"\"{exePath}\"";
        }

        throw new InvalidOperationException("Cannot determine how to launch the widget.");
    }
}
